import type { MealType, Recipe, RecipeIngredient, Taste } from '../domain/types';

/**
 * Curated seed library. Quantities are grams for the whole recipe; nutrition
 * is always computed from the ingredient table, never hand-entered.
 * Ingredient spec: [id, grams] or [id, grams, 'opt'].
 */
type Spec = [string, number] | [string, number, 'opt'];

const ing = (specs: Spec[]): RecipeIngredient[] =>
  specs.map(([ingredientId, grams, opt]) => ({ ingredientId, grams, ...(opt ? { optional: true } : {}) }));

const recipe = (
  id: string,
  title: string,
  summary: string,
  meta: { meals: MealType[]; tastes: Taste[]; servings: number; minutes: number },
  specs: Spec[],
  steps: string[],
): Recipe => ({
  id,
  title,
  summary,
  mealTypes: meta.meals,
  tastes: meta.tastes,
  servings: meta.servings,
  minutes: meta.minutes,
  ingredients: ing(specs),
  steps,
  source: 'seed',
});

